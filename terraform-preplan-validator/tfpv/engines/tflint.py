"""TFLint engine: terraform ruleset (recommended preset) + AWS ruleset.

Config selection (--tflint-config):
* auto (default): the project's .tflint.hcl if present, else the tfpv config;
* project / tfpv / <path>.
If the effective config does not enable the AWS ruleset, the `tflint_aws`
check is reported as skipped — the scan cannot be PASSED in that case.
"""
from __future__ import annotations

import json
import logging
import re
from pathlib import Path

from ..hcl.expr import literal
from ..hcl.parser import parse_text
from ..models import CheckRun, RawFinding, TIER_AWS, TIER_STATIC
from .base import EngineContext, timed

log = logging.getLogger("tfpv.tflint")

TFPV_CONFIG = """# Generated by tfpv (Terraform Pre-Plan Validator)
config {{
  call_module_type = "local"
}}

plugin "terraform" {{
  enabled = true
  preset  = "recommended"
}}

plugin "aws" {{
  enabled    = true
  version    = "{version}"
  source     = "github.com/terraform-linters/tflint-ruleset-aws"
  deep_check = {deep}
}}
"""
_VALUE_RE = re.compile(r'^"(?P<value>[^"]*)" is (?:an invalid value as (?P<attr>\w+)|previous generation|.*?deprecated)')


def _aws_enabled(config_text: str) -> bool:
    hf = parse_text(config_text, ".tflint.hcl")
    for b in hf.blocks:
        if b.type == "plugin" and b.labels and b.labels[0] == "aws":
            en = b.attributes.get("enabled")
            return en is None or literal(en.tokens) is True
    return False


def run(ctx: EngineContext) -> tuple[CheckRun, CheckRun]:
    check = CheckRun("tflint", "TFLint (terraform ruleset)", "tflint", TIER_STATIC)
    aws = CheckRun("tflint_aws", "TFLint AWS ruleset", "tflint", TIER_AWS if ctx.options.tflint_deep_check else TIER_STATIC)
    tflint = ctx.tool_path("tflint")

    def body() -> None:
        if "tflint" in ctx.options.skip:
            check.status = aws.status = "skipped"
            check.reason = aws.reason = "disabled with --skip"
            return
        if not tflint:
            check.status = aws.status = "skipped"
            check.reason = aws.reason = "tflint not found in PATH (use --tflint-bin)"
            return
        if ctx.project.root_module is None:
            check.status = aws.status = "skipped"
            check.reason = aws.reason = "no root module at the scanned path"
            return
        mode = ctx.options.tflint_config
        project_cfg = ctx.root / ".tflint.hcl"
        if mode not in ("auto", "project", "tfpv"):
            cfg = Path(mode).resolve()
        elif mode == "project" or (mode == "auto" and project_cfg.exists()):
            cfg = project_cfg
        else:
            cfg = ctx.tmp / "tflint.hcl"
            cfg.write_text(TFPV_CONFIG.format(version=ctx.options.tflint_aws_version, deep="true" if ctx.options.tflint_deep_check else "false"))
        if not cfg.exists():
            check.status = aws.status = "error"
            check.reason = aws.reason = f"TFLint config not found: {cfg}"
            return
        aws_on = _aws_enabled(cfg.read_text(encoding="utf-8", errors="replace"))
        ctx.shared["tflint_config"] = "project" if cfg == project_cfg else "tfpv" if cfg.parent == ctx.tmp else str(cfg)
        base = [tflint, f"--config={cfg}"]
        if not ctx.options.offline:
            init = ctx.runner.run(base + ["--init"], cwd=ctx.root, timeout=ctx.options.timeout_s)
            if init.returncode != 0:
                log.warning("tflint --init failed (plugins may already be installed): %s", (init.stderr or init.stdout).strip()[-200:])
        cmd = base + ["--format=json", "--no-color"] + [f"--var-file={v}" for v in ctx.options.var_files]
        check.command = " ".join(cmd)
        res = ctx.runner.run(cmd, cwd=ctx.root, timeout=ctx.options.timeout_s)
        try:
            data = json.loads(res.stdout) if res.stdout.strip() else {}
        except ValueError:
            data = {}
        errors = data.get("errors") or []
        if res.timed_out or (res.returncode not in (0, 2, 3) and not data):
            check.status = aws.status = "error"
            check.reason = aws.reason = (res.stderr.strip() or res.stdout.strip() or f"exit code {res.returncode}")[-300:]
            return
        for issue in data.get("issues") or []:
            r = issue.get("rule") or {}
            rng = issue.get("range") or {}
            msg = issue.get("message", "")
            m = _VALUE_RE.match(msg)
            f = RawFinding(engine="tflint", engine_rule=r.get("name", "tflint"), message=msg, file=rng.get("filename"),
                           line=(rng.get("start") or {}).get("line"), end_line=(rng.get("end") or {}).get("line"),
                           column=(rng.get("start") or {}).get("column"), engine_severity=r.get("severity"), link=r.get("link") or None,
                           value=m.group("value") if m else None, attribute=m.group("attr") if m and m.group("attr") else None,
                           extra={"callers": issue.get("callers") or []})
            (aws if f.engine_rule.startswith("aws_") else check).findings.append(f)
        if errors:
            msg = "; ".join((e.get("message") or e.get("summary") or "")[:200] for e in errors[:3])
            plugin_missing = any("plugin" in (e.get("message") or "").lower() for e in errors)
            check.status = "error"
            check.reason = msg
            if plugin_missing:
                aws.status, aws.reason = "error", f"{msg} — run `tflint --init` with network access"
        if not aws_on and aws.status == "pending":
            aws.status = "skipped"
            aws.reason = "the AWS ruleset is not enabled in the TFLint config used (.tflint.hcl): add plugin \"aws\" or use --tflint-config tfpv"
        ctx.shared["tflint_aws_enabled"] = aws_on

    timed(check, body)
    if aws.status == "pending":
        aws.status = "failed" if aws.findings else "passed"
    # TFLint reports only failures: a clean ruleset run counts as one passed check.
    for c in (check, aws):
        if c.status == "passed":
            c.passed_count = 1
    aws.duration_s = 0.0
    return check, aws
